function totalKills(g) {
  const kills = g?.player?.stats?.kills || {};
  return Object.values(kills).reduce((s, v) => s + v, 0);
}
function killCount(g, enemyId) {
  return g?.player?.stats?.kills?.[enemyId] || 0;
}

